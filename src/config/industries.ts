/**
 * Шаблоны под сферу бизнеса. Выбираются в онбординге и в «Настройки → Воронка»:
 * этапы, свои поля, товары, шаблоны ответов и демо-данные под нишу.
 *
 * Услуги идут в том же порядке, что SERVICES в lib/demo/catalog.ts: у каждой
 * позиции свой диапазон цен и длительность сделки, поэтому названия подобраны
 * так, чтобы им соответствовать.
 */
import type { CustomFieldEntity, CustomFieldType, OpenStageId } from "@/types/crm";
import { INDUSTRIES } from "@/lib/constants";
import { LEAD_MESSAGES, NOTE_TEMPLATES, SERVICES, TASK_TEMPLATES, DONE_TASKS } from "@/lib/demo/catalog";

export type IndustryLabel = (typeof INDUSTRIES)[number];

export interface FieldTemplate {
  key: string;
  entity: CustomFieldEntity;
  label: string;
  type: CustomFieldType;
  options?: string[];
  /** откуда брать значения для демо-данных */
  samples?: string[];
}

export interface IndustryPack {
  id: string;
  label: IndustryLabel;
  /** короткое имя для карточек выбора */
  short: string;
  example: string;
  /** позиции услуг, которые покупают компании; остальные — частные лица. "all" — только компании */
  b2bSlots: number[] | "all";
  stages: Record<OpenStageId, string>;
  services: string[];
  leadMessages: string[];
  taskTemplates: Record<OpenStageId, readonly [string, string, string]>;
  doneTasks: readonly string[];
  notes: { early: readonly string[]; late: readonly string[] };
  lostReasons: readonly [string, string, string, string, string, string];
  fields: FieldTemplate[];
  products: { name: string; price: number; unit: string }[];
  replyTemplates: { title: string; body: string }[];
  chat: {
    qualify: string[];
    /** ответ клиента на вопрос с тем же индексом */
    answers: string[];
    /** что отправляем клиенту, в винительном падеже: «коммерческое предложение», «смету» */
    proposal: string;
    reactions: string[];
    closeOffer: string;
    closeYes: string;
    paid: string;
  };
}

